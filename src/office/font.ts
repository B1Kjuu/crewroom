export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * 4 - 1;
}

/** Draws text with a 1px dark drop so it reads on any tile. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, drop = '#0b0f1a'): void {
  const draw = (ox: number, oy: number, fill: string) => {
    ctx.fillStyle = fill;
    [...text.toUpperCase()].forEach((ch, i) => {
      const g = GLYPHS[ch] ?? GLYPHS['?']!;
      g.forEach((row, gy) => {
        for (let gx = 0; gx < 3; gx++) if (row[gx] === '#') ctx.fillRect(x + ox + i * 4 + gx, y + oy + gy, 1, 1);
      });
    });
  };
  if (drop) draw(1, 1, drop);
  draw(0, 0, color);
}
